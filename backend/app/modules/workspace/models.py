from __future__ import annotations

from sqlalchemy import ForeignKey, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from app.infrastructure.database.base import Base, TimestampMixin, UUIDMixin


class FileRoot(UUIDMixin, TimestampMixin, Base):
    """A platform-managed logical file root.

    ``storage_path`` is always generated by the server and is relative to the
    configured storage directory; clients can never supply or override it.
    """

    __tablename__ = "file_roots"

    name: Mapped[str] = mapped_column(String(120), unique=True, index=True, nullable=False)
    description: Mapped[str] = mapped_column(Text, default="", nullable=False)
    owner_id: Mapped[str] = mapped_column(String(36), index=True, nullable=False)
    storage_path: Mapped[str] = mapped_column(String(512), unique=True, nullable=False)


class AgentFileRoot(UUIDMixin, TimestampMixin, Base):
    """Agent-to-file-root grant; the same root can be shared by many agents."""

    __tablename__ = "agent_file_roots"
    __table_args__ = (UniqueConstraint("agent_id", "root_id", name="uq_agent_file_root"),)

    agent_id: Mapped[str] = mapped_column(
        ForeignKey("agents.id", ondelete="CASCADE"), index=True, nullable=False
    )
    root_id: Mapped[str] = mapped_column(
        ForeignKey("file_roots.id", ondelete="CASCADE"), index=True, nullable=False
    )
    permission: Mapped[str] = mapped_column(String(16), default="read", nullable=False)


__all__ = ["AgentFileRoot", "FileRoot"]
